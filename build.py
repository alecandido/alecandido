#!/usr/bin/env python3
"""Assemble README.md from the pieces in content/.

    python3 build.py            # write README.md
    python3 build.py --check    # exit 1 if README.md is out of date

Standard library only (Python >= 3.11, for tomllib). What goes where:

    content/header.md       title and intro; `{{ banner }}` and `{{ links }}`
                            mark where the animation and the contact row go
    content/links.toml      the contact row: label, url, icon
    content/sections.toml   the sections, in order, each with its entries
    content/entries/*.yaml  one entry each, shown verbatim in a code block
    content/entries/*.md    free-form entries, included as they are
    content/logos.toml      the logo catalogue: light/dark files, link, height
    content/footer.md       optional closing lines

Images are referenced through ASSETS, an absolute URL, because GitHub does
not rewrite relative `srcset`s of dark-mode variants. Set README_ASSETS to
preview a branch.
"""

from __future__ import annotations

import os
import pathlib
import sys
import tomllib

ROOT = pathlib.Path(__file__).parent
CONTENT = ROOT / "content"
OUTPUT = ROOT / "README.md"

ASSETS = os.environ.get(
    "README_ASSETS", "https://raw.githubusercontent.com/alecandido/alecandido/master/assets/"
)
LOGO_HEIGHT = 56
ICON_HEIGHT = 18
GAP = "&emsp;&emsp;"

NOTICE = "<!-- Generated by build.py from content/, edit there and rebuild. -->"


def read(name: str) -> str:
    return (CONTENT / name).read_text(encoding="utf-8").strip()


def toml(name: str) -> dict:
    return tomllib.loads(read(name))


def img(src: str, alt: str, height: int, dark: str | None = None) -> str:
    """An <img>, wrapped in a <picture> when a dark-mode variant exists."""
    tag = f'<img src="{ASSETS}{src}" height="{height}" alt="{alt}">'
    if dark and dark != src:
        tag = (
            f'<picture><source media="(prefers-color-scheme: dark)" srcset="{ASSETS}{dark}">'
            f"{tag}</picture>"
        )
    return tag


def linked(inner: str, url: str | None) -> str:
    return f'<a href="{url}">{inner}</a>' if url else inner


def banner() -> str:
    return (
        '<p align="center">\n'
        f'  <img src="{ASSETS}psi.svg" width="100%" alt="A quantum wavepacket, oscillating">\n'
        "</p>"
    )


def links() -> str:
    items = []
    for link in toml("links.toml")["link"]:
        icon = img(f"icons/{link['icon']}.svg", "", ICON_HEIGHT)
        items.append(f"{linked(icon, link['url'])}&nbsp;{linked(link['label'], link['url'])}")
    return '<p align="center">\n  ' + f"\n  {GAP}\n  ".join(items) + "\n</p>"


def logos(ids: list[str], catalogue: dict) -> str:
    if not ids:
        return ""
    items = []
    for key in ids:
        logo = catalogue[key]
        tag = img(logo["light"], logo["alt"], logo.get("height", LOGO_HEIGHT), logo.get("dark"))
        items.append(linked(tag, logo.get("url")))
    return '<p align="center">\n  ' + f"\n  {GAP}\n  ".join(items) + "\n</p>"


def entry(spec: dict, catalogue: dict) -> str:
    name = spec["file"]
    body = read(f"entries/{name}")
    if name.endswith((".yaml", ".yml")):
        body = f"```yaml\n{body}\n```"
    return "\n\n".join(part for part in (body, logos(spec.get("logos", []), catalogue)) if part)


def section(spec: dict, catalogue: dict) -> str:
    title = spec.get("title")
    entries = "\n\n".join(entry(e, catalogue) for e in spec["entries"])
    if not spec.get("collapsible", True):
        return f"## {title}\n\n{entries}" if title else entries
    return (
        "<details>\n"
        f"  <summary><b>{title}</b></summary>\n\n"
        f"## {title}\n\n"
        f"{entries}\n\n"
        "</details>"
    )


def build() -> str:
    catalogue = toml("logos.toml")["logo"]
    header = read("header.md").replace("{{ banner }}", banner()).replace("{{ links }}", links())
    parts = [NOTICE, header]
    parts += [section(s, catalogue) for s in toml("sections.toml")["section"]]
    if (CONTENT / "footer.md").is_file():
        parts.append(read("footer.md"))
    return "\n\n".join(parts) + "\n"


def main() -> int:
    readme = build()
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != readme:
            print("README.md is out of date, run: python3 build.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(readme, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
